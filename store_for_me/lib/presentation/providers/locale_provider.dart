class LocaleNotifier extends StateNotifier<String> {
  static const String _key = 'app_language';

  LocaleNotifier() : super('en') {
    _loadLocale();
  }

  Future<void> _loadLocale() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final savedLang = prefs.getString(_key);
      if (savedLang != null && _translations.containsKey(savedLang)) {
        state = savedLang;
      }
    } catch (_) {}
  }

  Future<void> setLocale(String langCode) async {
    if (!_translations.containsKey(langCode)) return;
    state = langCode;
    try {
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_key, langCode);
    } catch (_) {}
  }

  String translate(String key, {String? fallback}) {
    final langMap = _translations[state] ?? _translations['en']!;
    return langMap[key] ?? fallback ?? _translations['en']![key] ?? key;
  }

